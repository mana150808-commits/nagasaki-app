// ホームの導入アニメを「アプリ起動時に一度だけ」再生するための状態。
//
// 判定は「アプリ内で一度でも別ルートへ遷移したか」で行う。
// - ページ読み込み直後（まだ何も遷移していない）→ 再生する
// - 一度でもマップ/アンケート等へ遷移したら以降は再生しない
//   （＝アプリ内でホームに戻っても再生しない）
// マウント回数に依存しないので、React StrictMode の二重マウントの影響を受けない。
// 完全リロード／PWA再起動時はモジュールが読み直され、再び再生される。

let navigatedAway = false

// 別ルートへ遷移したことを記録（App のルート監視から呼ぶ）
export const markNavigated = () => {
  navigatedAway = true
}

// このホーム表示で導入アニメを再生してよいか
export const shouldPlayIntro = () => !navigatedAway
